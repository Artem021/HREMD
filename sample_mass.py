def prep(x,y,start=None,end=None,npoints=10000):
    if start==None:
        start=round(min(x),1)
    if end==None:
        end=round(max(x),1)
    _x = np.linspace(start, end, npoints)# **10
    _y = np.interp(_x, x, y)
    print(f'values were interpolated; masses NOT converted in Da')
    # print(f'values were interpolated; masses converted in Da')
    return _x,_y

